// Deterministically attach authored sidecar data to existing stable Entry IDs.
// This script validates/copies content; it never invents or overwrites examples.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { lessonBundles } from '../src/content/lessons.ts'
import { discoverExampleCatalog, validateExampleCatalog } from './example-catalog.mjs'

const lessons = await discoverExampleCatalog()
const issues = validateExampleCatalog(lessons)
if (issues.length) throw new Error(issues.join('\n'))
const examples = {}
for (const bundle of lessonBundles) {
  const lessonNumber = Number(bundle.lesson.lessonId.match(/\d+$/u)[0])
  const catalog = lessons.find(lesson => lesson.catalog.lessonNumber === lessonNumber)?.catalog
  for (const entry of bundle.entries) {
    const word = (entry.nounData ? entry.nounData.article + ' ' : '') + entry.lemma
    const matches = catalog.entries.filter(row => row.word === word && row.meaningFa === entry.meaningFa)
    if (matches.length !== 1) throw new Error(`Ambiguous example mapping: ${entry.entryId}`)
    examples[entry.entryId] = matches[0].additionalExamples.map((example, index) => ({
      exampleId: `${entry.entryId}-additional-${index + 1}`, ...example,
    }))
    for (const example of examples[entry.entryId]) if (entry.examples.some(original => original.de.normalize('NFC').toLowerCase() === example.de.normalize('NFC').toLowerCase())) {
      throw new Error(`Additional example duplicates original: ${entry.entryId}`)
    }
  }
}
const output = '// Generated by npm run sync:examples from the checked-in sidecars. Do not edit.\n'
  + "import type { Example } from '../contracts/index.ts'\n\n"
  + 'export const additionalExamplesByEntry: Record<string, Example[]> = ' + JSON.stringify(examples, null, 2) + '\n'
const target = path.resolve('src/content/additional-examples.ts')
let previous
try { previous = await readFile(target, 'utf8') } catch { /* First generation. */ }
if (previous !== output) await writeFile(target, output)
await mkdir('test-results', { recursive: true })
const report = { lessonFiles: lessons.length, entries: lessons.reduce((sum, item) => sum + item.rows.length, 0),
  additionalExamples: lessons.reduce((sum, item) => sum + item.rows.length * 2, 0), activeEntries: Object.keys(examples).length,
  unprocessed: [], structuralValidation: 'passed', note: 'Structural validation is not a native-speaker grammar certification.' }
await writeFile('test-results/examples-report.json', JSON.stringify(report, null, 2))
console.log(JSON.stringify(report))
