export function withLessonSevenOrder(bundle: ContentBundle): ContentBundle {
  const ids: string[] = lessonSevenOrder.map(row => row.entryId)
  const update = (lesson: ContentBundle['lesson']) => lesson.lessonId === 'lesson-07'
    ? { ...lesson, studyEntryIds: ids, vocabularyEntryIds: ids } : lesson
  const refs = lessonSevenOrder.map(row => ({ sourceRefId: `${row.entryId}-coursebook-lesson-07`,
    sourceId: row.evidence === 'publisher-page-glossary' ? 'source-lesson-seven-glossary' : row.page ? 'source-textbook' : 'source-lesson-seven-supplement',
    lessonId: 'lesson-07', locator: row.sourceLocator }))
  const byId = new Map(refs.map((ref, index) => [ids[index], ref.sourceRefId]))
  return { ...bundle, lesson: update(bundle.lesson), lessons: bundle.lessons?.map(update),
    sources: [...bundle.sources,
      { sourceId: 'source-lesson-seven-glossary', kind: 'textbook', title: 'واژه‌نامهٔ رسمی ناشر · نگاشت صفحات کتاب درس۷', edition: null },
      { sourceId: 'source-lesson-seven-supplement', kind: 'workbook', title: 'واژه‌های تکمیلی کتاب تمرین و صوت درس۷', edition: null }],
    sourceRefs: [...bundle.sourceRefs, ...refs],
    entries: bundle.entries.map(entry => {
      const refId = byId.get(entry.entryId)
      return refId ? { ...entry, sourceRefIds: [...entry.sourceRefIds, refId],
        occurrences: entry.occurrences.map(item => item.lessonId === 'lesson-07' ? { ...item, sourceRefIds: [...item.sourceRefIds, refId] } : item) } : entry
    }) }
}
